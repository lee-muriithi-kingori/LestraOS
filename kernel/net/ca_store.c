#define CA_STORE_COUNT (sizeof(ca_store) / sizeof(ca_store[0]))

/* ===== Public API ===== */

/* Find a CA entry by common name.
 * Returns pointer to entry or NULL. */
const struct ca_entry* ca_store_find_by_name(const char* name) {
    for (uint32_t i = 0; i < CA_STORE_COUNT; i++) {
        if (strcmp(ca_store[i]->name, name) == 0)
            return ca_store[i];
    }
    return NULL;
}

/* Find a CA entry by SHA-256 fingerprint.
 * Returns pointer to entry or NULL. */
const struct ca_entry* ca_store_find_by_fingerprint(const uint8_t fp[32]) {
    for (uint32_t i = 0; i < CA_STORE_COUNT; i++) {
        if (memcmp(ca_store[i]->fingerprint, fp, 32) == 0)
            return ca_store[i];
    }
    return NULL;
}

/* Get the number of CA entries in the trust store. */
uint32_t ca_store_count(void) {
    return CA_STORE_COUNT;
}

/* Get a CA entry by index. Returns NULL if out of range. */
const struct ca_entry* ca_store_get(uint32_t index) {
    if (index >= CA_STORE_COUNT) return NULL;
    return ca_store[index];
}

/* Verify a certificate signature against a named CA.
 * Returns 1 if verified, 0 if CA not found or verification failed. */
int ca_store_verify_signature(const char* ca_name,
                              const uint8_t cert_hash[32],
                              const uint8_t signature[256]) {
    const struct ca_entry* ca = ca_store_find_by_name(ca_name);
    if (!ca) {
        pr_warn("ca_store: CA '%s' not found\n", ca_name);
        return 0;
    }

    /* ISRG Root X1 is RSA-4096, cannot verify with 2048-bit engine */
    uint8_t zero_mod[256];
    memset(zero_mod, 0, 256);
    if (memcmp(ca->modulus, zero_mod, 256) == 0) {
        pr_warn("ca_store: CA '%s' modulus not available (RSA-4096)\n", ca->name);
        return 0;
    }

    extern int rsa_verify_pkcs1_v15(const uint8_t*, const uint8_t*,
                                     const uint8_t*, uint32_t);
    return rsa_verify_pkcs1_v15(cert_hash, signature, ca->modulus, ca->exponent);
}
