/* Draw a bitmap icon at (x,y) with the given scale.
 * icon is a 32x32 array of palette indices (0-15). */
void fb_draw_icon(int x, int y, const uint8_t icon[32][32], int scale) {
    if (!fb_back) return;
    for (int row = 0; row < 32; row++) {
        for (int col = 0; col < 32; col++) {
            uint8_t pal_idx = icon[row][col];
            if (pal_idx == 0) continue;  /* transparent */
            uint32_t color = icon_palette[pal_idx];
            /* Draw scale*scale block */
            fb_fill_rect(x + col * scale, y + row * scale, scale, scale, color);
        }
    }
}

/* Get icon by index (0=terminal, 1=ai, 2=editor, 3=media, 4=files, 5=settings) */
const uint8_t (*icon_get(int idx))[32] {
    switch (idx) {
        case 0: return icon_terminal;
        case 1: return icon_ai;
        case 2: return icon_editor;
        case 3: return icon_media;
        case 4: return icon_files;
        case 5: return icon_settings;
        default: return icon_terminal;
    }
}
