/* Draw an app icon at (x,y) with the given scale. */
void app_icon_draw(int x, int y, const uint8_t icon[ICON_DIM][ICON_DIM], int scale) {
    for (int row = 0; row < ICON_DIM; row++) {
        for (int col = 0; col < ICON_DIM; col++) {
            uint8_t pal_idx = icon[row][col];
            if (pal_idx == 0) continue;
            uint32_t color = app_icon_palette[pal_idx];
            fb_fill_rect(x + col * scale, y + row * scale, scale, scale, color);
        }
    }
}

/* Get an app icon by name. Returns NULL if unknown. */
const uint8_t (*app_icon_get(const char* name))[32] {
    if (!name) return NULL;
    if (strcmp(name, "writer")    == 0) return icon_writer;
    if (strcmp(name, "calc")      == 0) return icon_calc;
    if (strcmp(name, "impress")   == 0) return icon_impress;
    if (strcmp(name, "video")     == 0) return icon_video;
    if (strcmp(name, "browser")   == 0) return icon_browser;
    if (strcmp(name, "mail")      == 0) return icon_mail;
    if (strcmp(name, "calendar")  == 0) return icon_calendar;
    if (strcmp(name, "photos")    == 0) return icon_photos;
    if (strcmp(name, "music")     == 0) return icon_music;
    if (strcmp(name, "launcher")  == 0) return icon_launcher;
    return NULL;
}
